pub(crate) fn is_builtin_function(name: &str) -> bool {
    let name = name.to_ascii_lowercase();
    SCALAR_FUNCTIONS.contains(&name.as_str()) || is_aggregating_function(&name)
}

pub(crate) fn is_aggregating_function(name: &str) -> bool {
    let name = name.to_ascii_lowercase();
    AGGREGATING_FUNCTIONS.contains(&name.as_str())
}
